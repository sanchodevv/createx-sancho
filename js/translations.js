function setLanguage(lang) {
  if (!translations[lang]) lang = "en";
  localStorage.setItem("app_lang", lang);
  document.documentElement.lang = lang;

  document.querySelectorAll("[t]").forEach((el) => {
    const key = el.getAttribute("t");
    if (!key) return;
    const text = translations[lang][key];
    if (text !== undefined) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        if (el.type === "button" || el.type === "submit") {
          el.value = text;
        } else {
          el.placeholder = text;
        }
      } else {
        el.innerHTML = text;
      }
    }
  });

  document.querySelectorAll(".lang-select").forEach((sel) => {
    sel.value = lang;
  });

  window.dispatchEvent(new CustomEvent("languageChanged", { detail: { lang } }));
}

window.getCurrentLang = function () {
  return localStorage.getItem("app_lang") || "en";
};

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("app_lang") || "en";
  setLanguage(savedLang);

  document.querySelectorAll(".lang-select").forEach((sel) => {
    sel.addEventListener("change", (e) => {
      setLanguage(e.target.value);
    });
  });

  function initBurgerMenus() {
    const burgerBtns = document.querySelectorAll("#burger-btn, .burger-btn");
    burgerBtns.forEach((btn) => {
      if (btn.dataset.burgerInit) return;
      btn.dataset.burgerInit = "true";

      btn.addEventListener("click", (e) => {
        e.stopPropagation();
        const header = btn.closest("header") || document;
        const mobileMenu = header.querySelector("#mobile-menu, .mobile-menu") || document.getElementById("mobile-menu");
        const burgerIcon = header.querySelector("#burger-icon, .burger-icon") || document.getElementById("burger-icon");
        const closeIcon = header.querySelector("#close-icon, .close-icon") || document.getElementById("close-icon");

        if (mobileMenu) {
          const isHidden = mobileMenu.classList.contains("hidden");
          if (isHidden) {
            mobileMenu.classList.remove("hidden");
            if (burgerIcon) burgerIcon.classList.add("hidden");
            if (closeIcon) closeIcon.classList.remove("hidden");
          } else {
            mobileMenu.classList.add("hidden");
            if (burgerIcon) burgerIcon.classList.remove("hidden");
            if (closeIcon) closeIcon.classList.add("hidden");
          }
        }
      });
    });
  }

  initBurgerMenus();

  window.addEventListener("resize", () => {
    if (window.innerWidth >= 1024) {
      document.querySelectorAll("#mobile-menu, .mobile-menu").forEach((menu) => {
        menu.classList.add("hidden");
      });
      document.querySelectorAll("#burger-icon, .burger-icon").forEach((icon) => {
        icon.classList.remove("hidden");
      });
      document.querySelectorAll("#close-icon, .close-icon").forEach((icon) => {
        icon.classList.add("hidden");
      });
    }
  });
});
